"""Writes docs/API.md and refreshes the endpoint table inside README.md.

Run it from the project folder (the one that contains the `app` folder):

    python scripts/generate_api_docs.py

It reads the routes straight from the running application, so the list can never be out of date.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.main import TAGS_METADATA, app  # noqa: E402

API_PREFIX = "/api/v1"
README_START, README_END = "<!-- API-START -->", "<!-- API-END -->"
METHOD_ORDER = {"GET": 0, "POST": 1, "PATCH": 2, "PUT": 3, "DELETE": 4}

# Who may call what. Routes under /admin and /worker follow their prefix; the rest are listed here.
# tests/test_route_matrix.py calls every endpoint with every role and checks that this table is true,
# so the documentation cannot drift away from the real behaviour.
SPECIAL_ROLES = {
    ("POST", "/api/v1/complaints"): "CITIZEN",
    ("GET", "/api/v1/complaints"): "ADMIN, CITIZEN",
    ("GET", "/api/v1/complaints/nearby"): "CITIZEN",
    ("GET", "/api/v1/complaints/{complaint_id}"): "ADMIN, CITIZEN",
    ("PATCH", "/api/v1/complaints/{complaint_id}"): "ADMIN",
    ("DELETE", "/api/v1/complaints/{complaint_id}"): "ADMIN",
    ("PATCH", "/api/v1/complaints/{complaint_id}/status"): "ADMIN",
    ("POST", "/api/v1/complaints/{complaint_id}/upvote"): "CITIZEN",
    ("DELETE", "/api/v1/complaints/{complaint_id}/upvote"): "CITIZEN",
    ("POST", "/api/v1/departments"): "ADMIN",
    ("PATCH", "/api/v1/departments/{department_id}"): "ADMIN",
    ("DELETE", "/api/v1/departments/{department_id}"): "ADMIN",
    ("POST", "/api/v1/categories"): "ADMIN",
    ("PATCH", "/api/v1/categories/{category_id}"): "ADMIN",
    ("DELETE", "/api/v1/categories/{category_id}"): "ADMIN",
}
PUBLIC_PATHS = {"/api/v1/auth/register", "/api/v1/auth/login"}


def who_can_call(method: str, path: str, needs_login: bool) -> str:
    """'Public', 'Any logged-in user', or a comma-separated list of roles."""
    if path in PUBLIC_PATHS or path.startswith(f"{API_PREFIX}/health"):
        return "Public"
    if (method, path) in SPECIAL_ROLES:
        return SPECIAL_ROLES[(method, path)]
    if path.startswith(f"{API_PREFIX}/admin"):
        return "ADMIN"
    if path.startswith(f"{API_PREFIX}/worker"):
        return "WORKER"
    return "Any logged-in user" if needs_login else "Public"


def collect_endpoints() -> list[dict]:
    """Reads the endpoints from the OpenAPI description FastAPI builds from the routes."""
    endpoints = []
    for path, operations in app.openapi()["paths"].items():
        if not path.startswith(API_PREFIX):
            continue
        for method, operation in operations.items():
            if method.upper() not in METHOD_ORDER:
                continue
            method = method.upper()
            endpoints.append(
                {
                    "method": method,
                    "path": path,
                    "summary": operation.get("summary", "").strip() or operation.get("operationId", ""),
                    "tag": (operation.get("tags") or ["Other"])[0],
                    "who": who_can_call(method, path, needs_login=bool(operation.get("security"))),
                    "query": [p["name"] for p in operation.get("parameters", []) if p["in"] == "query"],
                    "body": "requestBody" in operation,
                }
            )
    return endpoints


def _table(endpoints: list[dict]) -> str:
    lines = ["| Method | URL | Who can call it | What it does |", "|---|---|---|---|"]
    for e in endpoints:
        extra = f" Filters: {', '.join(f'`{q}`' for q in e['query'])}." if e["query"] else ""
        lines.append(f"| {e['method']} | `{e['path']}` | {e['who']} | {e['summary']}.{extra} |")
    return "\n".join(lines)


def build_tables() -> str:
    endpoints = collect_endpoints()
    tag_order = [t["name"] for t in TAGS_METADATA]
    descriptions = {t["name"]: t["description"] for t in TAGS_METADATA}
    tags = sorted({e["tag"] for e in endpoints}, key=lambda t: tag_order.index(t) if t in tag_order else 99)
    sections = []
    for tag in tags:
        group = sorted(
            (e for e in endpoints if e["tag"] == tag),
            key=lambda e: (e["path"].count("/") > 3, e["path"], METHOD_ORDER.get(e["method"], 9)),
        )
        sections.append(f"### {tag}\n\n{descriptions.get(tag, '')}\n\n{_table(group)}")
    return f"_{len(endpoints)} endpoints. Every URL starts with `http://127.0.0.1:8000` while you develop._\n\n" + "\n\n".join(sections)


API_MD_HEADER = """# API reference

This file is generated by `python scripts/generate_api_docs.py`. The live, clickable version is
Swagger at **http://127.0.0.1:8000/docs** (and ReDoc at `/redoc`).

## Responses

Success:

```json
{ "success": true, "message": "Complaint fetched", "data": { } }
```

Error (`errors` lists the problems when the input was invalid):

```json
{ "success": false, "message": "Validation failed", "errors": [ { "field": "email", "message": "value is not a valid email address" } ] }
```

| Code | Meaning |
|---|---|
| 200 / 201 | OK / created |
| 400 | An id in the URL is not a valid id |
| 401 | Not logged in, or the token is invalid or expired |
| 403 | Logged in, but your role may not do this |
| 404 | Not found (also used when the record belongs to someone else) |
| 409 | Conflict: duplicate, or a status change that is not allowed |
| 413 | Request body too large |
| 422 | The input is invalid |
| 429 | Too many login or register attempts. Wait for the `Retry-After` seconds |

## Logging in

1. `POST /api/v1/auth/register` (citizens only), or ask an admin for a worker account.
2. `POST /api/v1/auth/login` returns `data.accessToken`.
3. Send it with every other request: `Authorization: Bearer <accessToken>`.

```powershell
curl.exe -X POST http://127.0.0.1:8000/api/v1/auth/login -H "Content-Type: application/json" -d "{\\"email\\":\\"you@example.com\\",\\"password\\":\\"YourPassw0rd\\"}"
curl.exe http://127.0.0.1:8000/api/v1/auth/me -H "Authorization: Bearer PASTE_TOKEN_HERE"
```

## Reporting a complaint

`POST /api/v1/complaints` is a **multipart form**, not JSON: `title`, `description`, `categoryId`,
`latitude`, `longitude`, `photo` (png/jpg/webp, max 5 MB) and optional `isAnonymous`.
If a similar open complaint of the same category exists within 100 m, nothing is created and the answer
contains `duplicate: true` and the `upvoteUrl` instead.

## Endpoints

"""


def write_api_md(tables: str) -> None:
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "API.md").write_text(API_MD_HEADER + tables + "\n", encoding="utf-8")


def update_readme(tables: str) -> bool:
    readme = ROOT / "README.md"
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    pattern = re.compile(f"{re.escape(README_START)}.*?{re.escape(README_END)}", re.DOTALL)
    if not pattern.search(text):
        return False
    readme.write_text(pattern.sub(lambda _: f"{README_START}\n\n{tables}\n\n{README_END}", text), encoding="utf-8")
    return True


if __name__ == "__main__":
    tables = build_tables()
    write_api_md(tables)
    updated = update_readme(tables)
    count = len(collect_endpoints())
    print(f"docs/API.md written ({count} endpoints)" + ("; README.md endpoint list refreshed" if updated else ""))
